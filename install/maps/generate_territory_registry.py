"""Generate the offline territory registry from a reviewed Geofabrik index.

No downloads are performed. Pass a saved public index-v1.json as --input.
Provider ISO metadata is used before ancestry. Reviewed exceptions cover
multi-country extracts and source units whose ISO metadata is incomplete.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re

COLLECTIONS={'world','africa','antarctica','asia','australia-oceania','central-america',
             'europe','north-america','south-america'}
OVERRIDES={
    # These named extracts explicitly include multiple ISO countries/areas,
    # despite incomplete single-country metadata in the saved public index.
    'indonesia':('multi_country',['ID','TL']),
    'malaysia-singapore-brunei':('multi_country',['BN','MY','SG']),
    'guangdong':('multi_country',['CN','HK','MO']),
    # The Nusa-Tenggara source polygon includes Dili in Timor-Leste. Its other
    # six published Indonesian sibling units retain their reviewed ID owner.
    'nusa-tenggara':('multi_country',['ID','TL']),
    **{name:('subregion',['ID']) for name in ['java','kalimantan','maluku','papua','sulawesi','sumatra']},
    # Known ISO copy errors in the provider snapshot. American Oceania is a
    # composite extract whose individual coverage is not established here;
    # keep it navigation-only rather than inventing an owner/country list.
    'american-oceania':('collection',[]),
    'ile-de-clipperton':('subregion',['FR']),
    'polynesie-francaise':('country',['PF']),
    'tokelau':('country',['TK']),
    'wallis-et-futuna':('country',['WF']),
    'pitcairn-islands':('country',['PN']),
    'alps':('multi_country',['AT','CH','DE','FR','IT','LI','MC','SI']),
    'dach':('multi_country',['AT','CH','DE']),
    'britain-and-ireland':('multi_country',['GB','IE']),
    'ireland-and-northern-ireland':('multi_country',['GB','IE']),
    'guernsey-jersey':('multi_country',['GG','JE']),
    'south-africa-and-lesotho':('multi_country',['LS','ZA']),
    'comores':('multi_country',['KM','YT']),
    'sea':('multi_country',['BN','ID','KH','LA','MM','MY','PH','SG','TH','TL','VN']),
    'great-britain':('subregion',['GB']),
    'azores':('subregion',['PT']),
    'canary-islands':('subregion',['ES']),
    'isle-of-man':('country',['IM']),
    # XK is the source ecosystem's conventional user-assigned Kosovo code.
    'kosovo':('country',['XK']),
    **{name:('subregion',['US']) for name in ['us-midwest','us-northeast','us-pacific','us-south','us-west']},
}


def normalize(value):
    return re.sub(r'[^a-z0-9_-]','-',value.lower())


def classify(identity,by_id,seen=None):
    seen=set() if seen is None else seen
    if identity in seen:raise ValueError('Provider hierarchy contains a cycle')
    seen.add(identity)
    if identity in COLLECTIONS:return 'collection',[]
    if identity in OVERRIDES:return OVERRIDES[identity]
    properties=by_id.get(identity,{})
    countries=sorted(set(properties.get('iso3166-1:alpha2',[])))
    if countries:return ('country' if len(countries)==1 else 'multi_country'),countries
    countries=sorted({value[:2] for value in properties.get('iso3166-2',[]) if re.fullmatch(r'[A-Z]{2}-.+',value)})
    if countries:return ('subregion' if len(countries)==1 else 'multi_country'),countries
    parent=properties.get('parent')
    if parent in by_id:
        scope,countries=classify(parent,by_id,seen)
        if scope in ['country','subregion'] and len(countries)==1:return 'subregion',countries
    return 'collection',[]


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input',required=True,type=Path)
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[2]/'admin/app/data/map_region_territories.ts')
    args=parser.parse_args()
    source=json.loads(args.input.read_text(encoding='utf-8'))
    assert source['type']=='FeatureCollection'
    by_id={item['properties']['id']:item['properties'] for item in source['features']}
    registry={'world':{'territoryScope':'collection','countryCodes':[]}}
    for identity in sorted(by_id):
        scope,countries=classify(identity,by_id)
        assert all(re.fullmatch(r'[A-Z]{2}',country) for country in countries)
        registry[normalize(identity)]={'territoryScope':scope,'countryCodes':sorted(countries)}
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text('/** Offline Geofabrik territory snapshot. Generated by install/maps/generate_territory_registry.py.\n * Source: https://download.geofabrik.de/index-v1.json; ISO metadata plus reviewed extract exceptions.\n * Source units identify downloadable data, not a statement about political recognition. */\n'
        +'export const mapRegionTerritoryRegistry = '+json.dumps(registry,ensure_ascii=False,indent=2)+' as const\n',encoding='utf-8')
    print(json.dumps({'regions':len(registry),'scopes':dict(Counter(item['territoryScope'] for item in registry.values()))}))
